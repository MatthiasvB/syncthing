//go:build linux || solaris

package beacon

import "syscall"

// SO_REUSEADDR permits identical UDP bindings here, also across users.
// SO_REUSEPORT would not do: Linux only lets sockets of the same user share a
// port with it.
func reuseControl(_, _ string, c syscall.RawConn) error {
	var opErr error
	if err := c.Control(func(fd uintptr) {
		opErr = syscall.SetsockoptInt(int(fd), syscall.SOL_SOCKET, syscall.SO_REUSEADDR, 1)
	}); err != nil {
		return err
	}
	return opErr
}
